# -*- coding: utf-8 -*-
"""의복 11계층 — 계층이 실루엣을 정한다.

`docs/22-아트.md` 조합 구조의 두 번째 칸이다.

    체형(역할 5종) → 의복(계층 11종) → 소품(생업 47종) → 강조색 → 흐려짐

숫자는 새로 지어내지 않았다. `tools/sprite_gen.py` 의 2D 규격을 그대로 옮겼다.
아트 문서가 "옷단 높이 규격 고정"이라고 못박아 둔 이상, 2D 스프라이트와
3D 메시가 다른 길이를 쓰면 같은 인물이 두 사람이 된다.

2D 는 48x64 캔버스에 머리 y7, 발 y61 이다. 그래서 몸 높이가 54px 이고,
옷단 y 를 바닥에서 잰 비율로 바꾸면 (61 - y) / 54 다.

    long  57 -> 0.074      cape 50 -> 0.204      armor 41 -> 0.370
    hood  56 -> 0.093      coat 46 -> 0.278      tunic 40 -> 0.389
                            rag  44 -> 0.315

몸은 MPFB 가 옷 맞추라고 넣어 둔 케이지 두 개를 쓴다.
helper-tights(정점 2,674)가 몸에 붙는 옷, helper-skirt(720)가 퍼지는 치마다.
둘 다 뼈 웨이트가 이미 100% 칠해져 있어서 스키닝을 새로 할 일이 없다.
직접 원뿔을 깎는 것보다 이쪽이 낫다 — 메이크휴먼이 다리 사이가 어떻게
갈라져야 하는지 이미 풀어 뒀다.
"""

# 계층 -> 옷 모양. tools/sprite_gen.py 의 ROBE 와 같아야 한다.
ROBE = {
    "왕실": "long", "귀족": "cape", "술사": "hood", "성직": "hood",
    "관리": "coat", "상인": "coat", "장인": "tunic", "농어민": "tunic",
    "병졸": "armor", "하인": "tunic", "유랑": "rag",
}

# 옷 모양 -> 밑단 높이(바닥에서 잰 키 대비 비율). 위 표에서 옮긴 값.
HEM = {"long": 0.074, "hood": 0.093, "cape": 0.204,
       "coat": 0.278, "rag": 0.315, "armor": 0.370, "tunic": 0.389}

# 옷 모양 -> 소매 길이. 어깨(0)에서 손목(1) 사이 어디서 자르는가.
# 소매가 늘어지는가. 앞 실루엣에서 팔이 "맨팔"로 보이면 계층이 안 읽힌다.
# 처음엔 소매 길이(SLEEVE)만 두었는데, 길이는 실루엣에 거의 안 나왔다 —
# 어차피 팔 굵기가 그대로라 옷을 입었는지 알 수가 없었다.
# 그래서 축 둘레로 부풀리고 손목 쪽을 흘러내리게 하는 값을 따로 둔다. 미터.
DRAPE = {"long": 0.072, "hood": 0.066, "cape": 0.038}

# 어깨 갑옷. 병졸만. 앞에서 보면 어깨가 튀어나온 것으로 즉시 갈린다 —
# 병졸의 밑단(0.370)은 장인·농어민·하인의 tunic(0.389)과 거의 같아서
# 밑단으로는 절대 구별되지 않는다.
PAULDRON = {"armor": 0.062}

# 한쪽 어깨가 드러난다. 유랑만. 좌우가 다른 실루엣은 다른 여섯과 섞이지 않는다.
BARE = {"rag": True}

SLEEVE = {"long": 1.00, "hood": 1.00, "cape": 0.92,
          "coat": 0.82, "armor": 0.52, "tunic": 0.44, "rag": 0.34}

# 치마 케이지를 쓰는 옷. 밑단이 무릎 아래로 내려가는 것만 쓴다 —
# 그 위로 짧은 옷에 치마를 붙이면 다리 사이가 막힌 자루가 된다.
SKIRT = {"long": True, "hood": True, "cape": True,
         "coat": False, "rag": False, "armor": False, "tunic": False}

HOOD = {"hood": True}          # 술사 · 성직
CAPE = {"cape": True}          # 귀족

# 계층별 부피감. PUFF 는 살에서 얼마나 띄우는가(m), THICK 는 천 두께(m).
# 위로 갈수록 옷이 두껍고 풍성하다 — 실루엣만으로 계층이 읽혀야 한다.
PUFF = {"왕실": 0.038, "귀족": 0.032, "술사": 0.030, "성직": 0.026,
        "관리": 0.020, "상인": 0.020, "장인": 0.012, "병졸": 0.024,
        "농어민": 0.012, "하인": 0.009, "유랑": 0.016}
THICK = {"왕실": 0.018, "귀족": 0.016, "술사": 0.015, "성직": 0.014,
         "관리": 0.012, "상인": 0.012, "장인": 0.009, "병졸": 0.022,
         "농어민": 0.009, "하인": 0.007, "유랑": 0.011}

# 강조색이 들어가는 자리. 2D 에서 왕실·귀족은 어깨 장식, 병졸은 흉갑선이었다.
# 여기서는 머티리얼 슬롯 1번으로 뺀다 — 유니티에서 인물의 key_color 를
# 그 슬롯에만 넣으면 "짙은 실루엣 + 강조색 하나"가 그대로 성립한다.
#   (아래, 위) — 바닥에서 잰 키 대비 비율. None 이면 강조 부위 없음.
ACCENT = {
    "왕실": (0.780, 0.840),   # 어깨 장식
    "귀족": (0.780, 0.840),   # 어깨 장식
    "술사": None,
    "성직": (0.640, 0.690),   # 허리끈
    "관리": (0.620, 0.660),   # 띠
    "상인": (0.600, 0.640),   # 전대
    "장인": (0.590, 0.630),   # 앞치마 끈
    "농어민": None,
    "병졸": (0.690, 0.760),   # 흉갑선
    "하인": None,
    "유랑": None,
}

# 유랑만 밑단이 고르지 않다. 2D 에서도 rag 만 몸통 다각형이 들쭉날쭉했다.
RAGGED = "유랑"

# 파일 이름용.
SLUG = {"왕실": "royal", "귀족": "noble", "술사": "mage", "성직": "clergy",
        "관리": "clerk", "상인": "merchant", "장인": "artisan",
        "병졸": "soldier", "농어민": "peasant", "하인": "servant",
        "유랑": "vagrant"}


def spec(cls):
    """계층 하나의 규격을 한 덩어리로."""
    robe = ROBE[cls]
    return dict(
        cls=cls, slug=SLUG[cls], robe=robe,
        hem=HEM[robe], sleeve=SLEEVE[robe], skirt=SKIRT[robe],
        hood=HOOD.get(robe, False), cape=CAPE.get(robe, False),
        drape=DRAPE.get(robe, 0.0), pauldron=PAULDRON.get(robe, 0.0),
        bare=BARE.get(robe, False),
        puff=PUFF[cls], thick=THICK[cls], accent=ACCENT[cls],
        ragged=(cls == RAGGED),
    )
