# 등급별 총 스탯 포인트(평균 기준선). 개체는 이 총합 ±6% 안에서 흔들린다.
RARITY_POOL = {1:180, 2:235, 3:305, 4:400, 5:540}
ROLE_BIAS = {
 "수호":{"잔존":1.45,"의지":0.70,"자취":1.55,"공명":0.75},
 "저항":{"잔존":0.90,"의지":1.70,"자취":0.80,"공명":1.05},
 "헌신":{"잔존":1.30,"의지":0.95,"자취":1.00,"공명":1.15},
 "탐구":{"잔존":0.85,"의지":1.15,"자취":0.85,"공명":1.60},
 "도피":{"잔존":0.75,"의지":1.25,"자취":0.70,"공명":1.85},
}
def roll_stats(rarity, role):
    pool = RARITY_POOL[rarity] * random.uniform(0.94, 1.06)
    w = {s: ROLE_BIAS[role][s] * random.uniform(0.72, 1.34) for s in STATS}
    tot = sum(w.values())
    st = {s: max(1, round(pool * w[s] / tot)) for s in STATS}
    st["잔존"] *= 7           # HP 스케일
    gr = {s: round(st[s] * random.uniform(0.030, 0.078), 2) for s in STATS}  # 개체별 성장 계수
    return st, gr

