def make_skills(t, role, era, floor):
    n = random.choice([3,4])
    pool = list(SKILL_CORE[role])
    if random.random() < .45:                      # 가끔 다른 역할의 재능이 섞인다
        pool += random.sample(SKILL_CORE[random.choice([r for r in ROLES if r!=role])], 2)
    picked = random.sample(pool, k=min(n, len(pool)))
    motifs = random.sample(MOTIF[t["n"]], k=len(picked))
    out, seen = [], set()
    for (verb, eff), mo in zip(picked, motifs):
        if verb in seen: continue
        seen.add(verb)
        bl = random.choice(BLOOM)
        v = random.choice([12,15,18,20,24,28,32,40])
        cond = random.choice([f"{era} 층", f"뜰에 {t['g']} 배치 중", "아군 3명 이하",
                              f"{max(1,floor-5)}~{min(99,floor+5)}층", "잔존 절반 이하"])
        out.append({"name": f"{mo}", "verb": verb, "effect": eff.format(v=v), "bloom": bl,
                    "note": random.choice(BLOOM_NOTE[bl]).format(cond=cond)})
    return out

