def pick(d):
    x,a=random.random(),0.0
    for k,v in sorted(d.items()):
        a+=v
        if x<=a: return k
    return max(d)

def gen(rarity=None):
    t = random.choice(T)
    era = random.choice([e for e in ERAS if e in t["eras"]])
    lo,hi = ERAS[era]; floor = random.randint(lo,hi)
    role = random.choice(ROLES)
    rar = rarity if rarity else pick(PULL)
    bondi = pick(BONDI[rar])
    daily = random.choice([d for d,ok in t["daily"] if ok is None or era in ok])
    habit, asname = random.choice(t["habit"])
    name = real_name() if rar>=3 else asname
    title = f"{era}의 {t['n']}" if rar>=3 else f"{floor}층 · 이름이 남지 않음"
    life = f"{random.choice(ERA_OPEN[era])}. {daily}. {habit}."
    tpl = random.choice(END[role])
    tgt = t["place"] if "{place}{을}" in tpl else t["obj"]
    death = (tpl.format(place=t["place"], obj=t["obj"], 을=josa(tgt,"을","를")).replace("  "," ")
             + ". " + random.choice(TAIL[role]) + ".")
    st, gr = roll_stats(rar, role)
    return {"name":name,"title":title,"rarity":rar,"bondi":bondi,"role":role,"era":era,
            "floor":floor,"trade":t["n"],"garden":t["g"],"life":life,"death":death,
            "stats":st,"growth":gr,"skills":make_skills(t,role,era,floor)}

