def pick(d):
    x,a=random.random(),0.0
    for k,v in sorted(d.items()):
        a+=v
        if x<=a: return k
    return max(d)

def make_name():
    return random.choice(SYL_A)+random.choice(SYL_B)

def generate():
    t=random.choice(TRADES); era=random.choice(list(ERAS)); lo,hi=ERAS[era]
    floor=random.randint(lo,hi); role=random.choice(list(ENDS))
    place=PLACES[t["n"]]; obj=t["obj"]
    rar=pick(PULL); bondi=pick(BONDI[rar])
    named = rar>=3
    name = make_name() if named else random.choice([f"{floor}층의 {t['n']}","이름이 남지 않은 사람","누군가의 이웃"])
    title = f"{era}의 {t['n']}" if named else "이름이 남지 않음"
    life = (f"{random.choice(ERA_OPEN[era])} "
            f"{random.choice(t['daily'])}. {random.choice(t['habit'])}.")
    e=ENDS[role]
    death = (random.choice(e["tpl"]).format(place=place,obj=obj) + ". " + random.choice(e["tail"]) + ".")
    talents=random.sample(BLOOM, k=random.choice([3,4]))
    return {"name":name,"title":title,"rarity":rar,"bondi":bondi,"role":role,
            "floor":floor,"era":era,"trade":t["n"],"garden":t["g"],
            "life":life,"death":death,"talents":talents,"obj":obj}

