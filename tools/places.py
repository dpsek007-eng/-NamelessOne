#          그래서 등을 돌리고 허공을 두들겼다.
#  work  : 연장이 놓이는 자리. 손 높이다. 휘두르는 손이 여기를 지난다.
#  parts : 덩이 목록.

def _gate():
    p = []
    for sy in (-1, 2):                                   # 문 양옆 두 탑
        p += [box(0, sy, 0, 0.95, 0.95, 3.1, 0),
              box(0, sy, 3.1, 1.15, 1.15, 0.28, 0)]
        for i in (-1, 1):                                # 총안
            p.append(box(i * 0.32, sy, 3.38, 0.34, 1.05, 0.3, 0))
    p.append(box(0, 0.5, 3.1, 0.75, 2.1, 0.5, 0))        # 상인방
    p.append(box(0, 0.5, 3.6, 0.5, 1.9, 0.22, 0))
    return p

