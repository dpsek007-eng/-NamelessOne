#  foot  : 이 일터가 차지하는 칸 (일터 칸에서 본 상대 좌표). 지도에 '#' 로 찍힌다.
#          찍고 나서 성문에서 열네 곳에 다 걸어갈 수 있는지 make_garden.check() 가 잰다.
