    npk=3+r.i(2); base=list(SKILL[role])
    if r.f()<0.45: base+=r.sample(SKILL[r.pick([x for x in ROLES if x!=role])],2)
    picks=r.sample(base,npk); motifs=r.sample(t["motif"],npk)
